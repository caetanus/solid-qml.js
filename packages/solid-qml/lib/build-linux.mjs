// `solid-qml build --target linux` — packaging is ASSEMBLY, not compilation: the transpiled app
// (QML + CSS sidecar + mirrored modules + public/ assets) plus the prebuilt
// @solid-qml/runtime-linux-x64 payload (loader + libsolidqml + Qt 6.11.2 runtime) become
//   dist/linux/<Product>-x86_64.AppImage           (single file; type-2 runtime, static)
//   dist/linux/<Product>-<version>-linux-x86_64.tar.gz   (portable directory, ./AppRun)
import { execFile } from "node:child_process";
import { cp, mkdir, readFile, rm, writeFile, chmod, stat } from "node:fs/promises";
import path from "node:path";
import { promisify } from "node:util";
import { generateApp } from "./generate.mjs";
import { loadProject, CliError } from "./project.mjs";
import { findRuntime, TARGETS } from "./runtime.mjs";
import { ensureTool } from "./tools.mjs";

const run = promisify(execFile);

const appRun = (project) => `#!/bin/sh
# ${project.productName} ${project.version} — generated by solid-qml build --target linux.
HERE="$(dirname "$(readlink -f "$0")")"
exec "$HERE/usr/lib/solid-qml/solid-qml-run" --app-name ${JSON.stringify(project.appId)} \\
  --qml "$HERE/usr/share/${project.appId}/App.generated.qml" "$@"
`;

const desktopFile = (project) => `[Desktop Entry]
Type=Application
Name=${project.productName}
Exec=${project.appId}
Icon=${project.appId}
Categories=${project.categories.endsWith(";") ? project.categories : `${project.categories};`}
Terminal=false
StartupWMClass=${project.appId}
X-AppImage-Version=${project.version}
`;

const mb = (n) => `${(n / 1048576).toFixed(1)} MB`;

export async function buildLinux(opts) {
  const project = await loadProject(opts.cwd);
  const runtime = findRuntime(project.dir, TARGETS.linux);
  const outDir = path.resolve(project.dir, opts.outDir ?? "dist/linux");
  const stageRoot = path.join(project.workDir, "build", "linux");
  const dirName = `${project.fileName}-${project.version}-linux-x86_64`;
  const appDir = path.join(stageRoot, dirName);
  await rm(stageRoot, { recursive: true, force: true });
  await mkdir(appDir, { recursive: true });
  await mkdir(outDir, { recursive: true });

  // 1. The app: transpile into usr/share/<appId>.
  const share = path.join(appDir, "usr/share", project.appId);
  const gen = await generateApp(project, share);
  console.log(`[solid-qml] transpiled ${path.relative(project.dir, project.entry)} → ${gen.components} components + ${gen.modules} modules + css (${gen.cssBytes}b)`);

  // 2. The runtime payload, verbatim (symlinks kept: Qt's lib*.so.6 → lib*.so.6.11.2).
  await cp(runtime.root, path.join(appDir, "usr/lib/solid-qml"), { recursive: true, verbatimSymlinks: true });
  console.log(`[solid-qml] runtime ${runtime.manifest.name}@${runtime.manifest.version} (Qt ${runtime.manifest.qt}, glibc >= ${runtime.manifest.glibc})`);

  // 3. AppDir metadata: AppRun, .desktop, icon (+ .DirIcon), license notices.
  await writeFile(path.join(appDir, "AppRun"), appRun(project));
  await chmod(path.join(appDir, "AppRun"), 0o755);
  await writeFile(path.join(appDir, `${project.appId}.desktop`), desktopFile(project));
  await mkdir(path.join(appDir, "usr/share/applications"), { recursive: true });
  await writeFile(path.join(appDir, "usr/share/applications", `${project.appId}.desktop`), desktopFile(project));
  const iconExt = path.extname(project.icon).toLowerCase();
  if (![".svg", ".png"].includes(iconExt)) throw new CliError(`icon must be .svg or .png: ${project.icon}`);
  const icon = await readFile(project.icon);
  await writeFile(path.join(appDir, `${project.appId}${iconExt}`), icon);
  await writeFile(path.join(appDir, ".DirIcon"), icon);
  const iconDir = iconExt === ".svg" ? "scalable" : "256x256";
  await mkdir(path.join(appDir, "usr/share/icons/hicolor", iconDir, "apps"), { recursive: true });
  await writeFile(path.join(appDir, "usr/share/icons/hicolor", iconDir, "apps", `${project.appId}${iconExt}`), icon);

  // 4. Portable tarball (the AppDir itself; run ./AppRun).
  const tarball = path.join(outDir, `${dirName}.tar.gz`);
  await run("tar", ["-C", stageRoot, "-czf", tarball, dirName]);
  console.log(`[solid-qml] wrote ${path.relative(project.dir, tarball)} (${mb((await stat(tarball)).size)})`);

  if (opts.appimage === false) return;

  // 5. AppImage via pinned appimagetool + type-2 runtime (no FUSE needed on the build host).
  const appimagetool = await ensureTool("appimagetool");
  const rtFile = await ensureTool("appimageRuntime");
  const appImage = path.join(outDir, `${project.fileName}-x86_64.AppImage`);
  const tmp = path.join(project.workDir, "tmp");
  await mkdir(tmp, { recursive: true });
  await rm(appImage, { force: true });
  try {
    await run(appimagetool, ["--appimage-extract-and-run", "--no-appstream", "--runtime-file", rtFile, appDir, appImage], {
      env: { ...process.env, ARCH: "x86_64", VERSION: project.version, TMPDIR: tmp, APPIMAGE_EXTRACT_AND_RUN: "1" },
      cwd: tmp,
      maxBuffer: 64 * 1024 * 1024,
    });
  } catch (err) {
    throw new CliError(`appimagetool failed:\n${err.stdout ?? ""}${err.stderr ?? err.message}`);
  }
  await rm(tmp, { recursive: true, force: true });
  console.log(`[solid-qml] wrote ${path.relative(project.dir, appImage)} (${mb((await stat(appImage)).size)})`);
}
