// Runtime support emitted next to the generated QML, only when an app needs it.

/** Where the batch runtime is written, relative to the generated QML (beside the mirrored npm
 *  modules). One ES module instance per QML engine: every component imports the same state. */
export const BATCH_MODULE_PATH = "modules/solid-batch.mjs";

/** `batch(fn)`: while `fn` runs, computations (createEffect & co.) that a write would re-run are
 *  queued instead (once each), and run when the outermost batch ends — as in Solid, where an
 *  effect sees the final state, not each intermediate write. QML bindings (render, createMemo)
 *  still update on each write: they are synchronous and side-effect free, so only their final
 *  value is observable. A computation whose component was destroyed meanwhile is skipped. */
export const BATCH_MODULE_SOURCE = `// Generated by the transpiler (solid-qml batch runtime). Do not edit by hand.
let depth = 0;
const queue = [];

export function batch(fn) {
  depth++;
  try {
    return fn();
  } finally {
    depth--;
    if (depth === 0) flush();
  }
}

export function defer(obj, method) {
  if (depth === 0) return false;
  for (let i = 0; i < queue.length; i++) if (queue[i].o === obj && queue[i].m === method) return true;
  queue.push({ o: obj, m: method });
  return true;
}

function flush() {
  depth++;
  try {
    while (queue.length) {
      const q = queue.shift();
      if (q.o && typeof q.o[q.m] === "function") q.o[q.m]();
    }
  } finally {
    depth--;
  }
}
`;
