#!/usr/bin/env node
// Generates the results section of docs/performance.md from raw runner output (scripts/bench/run.mjs).
// Usage: node scripts/bench/report.mjs bench/results/<file>.json [--doc docs/performance.md]
// Replaces everything between <!-- results:begin --> and <!-- results:end --> in the doc; with no
// --doc, prints the section to stdout. Statistics use warm rounds only (round 0 = warm-up), except
// the "cold" column, which is round 0 across processes.
import fs from "node:fs";
import path from "node:path";

const argv = process.argv.slice(2);
const docIdx = argv.indexOf("--doc");
const doc = docIdx >= 0 ? argv.splice(docIdx, 2)[1] : null;
const files = argv;
if (!files.length) throw new Error("usage: report.mjs <results.json> [more.json…] [--doc docs/performance.md]");
// Several files (a main run + re-measurements with --only) merge into one data set; any process run
// that overlapped a build is EXCLUDED from the statistics (it stays in the raw data).
const all = files.map((x) => JSON.parse(fs.readFileSync(x, "utf8")));
const file = files.join("`, `");
const R = {
  environment: all[0].environment,
  batches: all.flatMap((x, i) => x.batches.map((b) => (i ? { ...b, label: `${b.label} (re-measure, ${x.environment.date.slice(0, 16)}Z)` } : b))),
  runs: all.flatMap((x) => x.runs),
  mem: all.flatMap((x) => x.mem ?? []),
};
const excluded = [...R.runs, ...R.mem].filter((r) => r.overlappedBuild);
R.runs = R.runs.filter((r) => !r.overlappedBuild);
R.mem = R.mem.filter((r) => !r.overlappedBuild);
const envMismatch = all.filter((x) => x.environment.build.libSha256 !== R.environment.build.libSha256 || x.environment.chromium !== R.environment.chromium);
if (envMismatch.length) throw new Error("merged files come from different builds/browsers");
const OPS = ["create1k", "update10th", "swap", "remove1", "append1k", "clear"];
const OP_LABEL = {
  create1k: "create N rows", update10th: "update every 10th", swap: "swap rows 1↔998",
  remove1: "remove one row", append1k: "append 1,000 rows", clear: "clear",
};

const sorted = (a) => [...a].sort((x, y) => x - y);
const median = (a) => {
  if (!a.length) return null;
  const s = sorted(a);
  const m = s.length >> 1;
  return s.length % 2 ? s[m] : (s[m - 1] + s[m]) / 2;
};
const pct = (a, p) => (a.length ? sorted(a)[Math.min(a.length - 1, Math.ceil((p / 100) * a.length) - 1)] : null);
const min = (a) => (a.length ? Math.min(...a) : null);
const f = (x) => (x == null ? "—" : x >= 100 ? x.toFixed(0) : x >= 10 ? x.toFixed(1) : x.toFixed(2));

function samples(target, n, scroll, key, op, metric, warm = true) {
  const out = [];
  for (const r of R.runs)
    if (r.target === target && r.n === n && r.scroll === scroll && !!r.key === key)
      for (const s of r.samples) if (s.op === op && s.warmup === !warm) out.push(s[metric]);
  return out;
}
const stat = (a) => ({ n: a.length, med: median(a), p95: pct(a, 95), min: min(a) });
// "node /path/to/thing.js --x" → "node thing.js"; "/usr/lib/chromium/chromium --type=renderer" → "chromium (renderer)".
const shortCmd = (c) => {
  if (c.startsWith("[")) return c.split(/\s/)[0];
  const t = c.split(/\s+/);
  const base = (x) => (x ?? "").split("/").pop();
  const type = /--type=([\w-]+)/.exec(c)?.[1];
  if (/^(node|python3?|sh|bash|zsh)$/.test(base(t[0])) && t[1]) return `${base(t[0])} ${base(t.find((x, i) => i > 0 && !x.startsWith("-")))}`;
  return base(t[0]) + (type ? ` (${type})` : "");
};
const has = (target, key) => R.runs.some((r) => r.target === target && !!r.key === key);

const sizes = [...new Set(R.runs.map((r) => r.n))].sort((a, b) => a - b);
const scrolls = ["auto", "visible"].filter((s) => R.runs.some((r) => r.scroll === s));
const scrollName = { auto: "scrolling list (`overflow-y: auto`) — native virtualizes", visible: "non-scrolling list (`overflow-y: visible`) — native is eager" };

const lines = [];
const E = R.environment;
lines.push(`Generated by \`scripts/bench/report.mjs\` from \`${file}\`` +
  ` (raw samples in the JSON and the CSVs next to it).`, "");
lines.push("**Environment of this run**", "");
lines.push(`| | |`, `|---|---|`);
lines.push(`| date | ${E.date} |`);
lines.push(`| machine | ${E.cpu}, ${E.cpuCount} logical CPUs, ${(E.memTotalMiB / 1024).toFixed(0)} GiB RAM, governor \`${E.cpuGovernor}\` |`);
lines.push(`| OS | ${E.os}, Linux ${E.kernel} |`);
lines.push(`| Qt | ${E.qt} |`);
lines.push(`| Chromium | ${E.chromium} (headless=new) |`);
lines.push(`| Node | ${E.node} |`);
lines.push(`| solid-qml | ${E.gitSha?.slice(0, 10)}${E.gitDirty ? " (+ uncommitted bench changes)" : ""}, engine ${E.engineSha?.slice(0, 10)} |`);
lines.push(`| native build | \`${E.build.buildtype}\` (-O${E.build.optimization}, qml_debug=${E.build.qmlDebug}), libsolidqml sha256 ${E.build.libSha256}… |`);
lines.push(`| native renderer | ${Object.entries(E.native.env).map(([k, v]) => `${k}=${v}`).join(" ")} (nothing is rasterized) |`);
lines.push(`| samples | ${E.params.reps} processes × ${E.params.rounds - 1} warm rounds per op (+1 warm-up round each); memory/startup: ${E.params.memReps} processes |`);
lines.push("");

for (const n of sizes)
  for (const scroll of scrolls) {
    lines.push(`### ${n.toLocaleString("en-US")} rows — ${scrollName[scroll]}`, "");
    const withKey = has("native", true);
    lines.push("Synchronous time (ms; state write → returns, layout settled). Warm rounds.", "");
    lines.push(`| operation | native median | p95 | min | cold¹ |${withKey ? " native `key=\"id\"` median | p95 |" : ""} web median | p95 | min | cold¹ | median ratio web/native |`);
    lines.push(`|---|---:|---:|---:|---:|${withKey ? "---:|---:|" : ""}---:|---:|---:|---:|---:|`);
    for (const op of OPS) {
      const a = stat(samples("native", n, scroll, false, op, "sync"));
      const ac = median(samples("native", n, scroll, false, op, "sync", false));
      const k = stat(samples("native", n, scroll, true, op, "sync"));
      const w = stat(samples("web", n, scroll, false, op, "sync"));
      const wc = median(samples("web", n, scroll, false, op, "sync", false));
      const ratio = a.med && w.med ? (w.med / a.med) : null;
      const rtxt = ratio == null ? "—" : ratio >= 1 ? `**${ratio.toFixed(1)}× (native faster)**` : `${(1 / ratio).toFixed(1)}× slower`;
      lines.push(`| ${OP_LABEL[op]} | ${f(a.med)} | ${f(a.p95)} | ${f(a.min)} | ${f(ac)} |${withKey ? ` ${f(k.med)} | ${f(k.p95)} |` : ""} ${f(w.med)} | ${f(w.p95)} | ${f(w.min)} | ${f(wc)} | ${rtxt} |`);
    }
    lines.push("");
    lines.push("Until the next presented frame and until the next timer turn (ms; medians, p95 in parentheses).", "");
    lines.push(`| operation | native frame | web frame (double rAF) | native +tick | web +tick |`);
    lines.push(`|---|---:|---:|---:|---:|`);
    for (const op of OPS) {
      const nf = stat(samples("native", n, scroll, false, op, "frame"));
      const wf = stat(samples("web", n, scroll, false, op, "frame"));
      const nt = stat(samples("native", n, scroll, false, op, "tick"));
      const wt = stat(samples("web", n, scroll, false, op, "tick"));
      lines.push(`| ${OP_LABEL[op]} | ${f(nf.med)} (${f(nf.p95)}) | ${f(wf.med)} (${f(wf.p95)}) | ${f(nt.med)} (${f(nt.p95)}) | ${f(wt.med)} (${f(wt.p95)}) |`);
    }
    lines.push("");
  }
lines.push("¹ cold = round 0 of each process (first time the operation runs in that process), median across processes.", "");

if (R.mem?.length) {
  lines.push("### Memory per row and startup", "");
  lines.push("PSS growth from an empty list to 2,000 mounted rows (unique labels), 3 s after mounting. Native: the" +
    " whole loader process. Web: the renderer process with the largest growth (the method used throughout the" +
    " project); \"all processes\" adds the browser, GPU and utility processes' growth.", "");
  lines.push("| target | list | KB/row median (min–max) | all processes KB/row | process PSS after, MB | startup → mounted, ms median (p95) | runs |");
  lines.push("|---|---|---:|---:|---:|---:|---:|");
  for (const scroll of ["auto", "visible"])
    for (const target of ["native", "web"]) {
      const m = R.mem.filter((x) => x.target === target && x.scroll === scroll && x.complete);
      if (!m.length) continue;
      const pr = m.map((x) => x.perRowKB);
      const tr = m.map((x) => x.treePerRowKB);
      const st = m.map((x) => x.startupMs);
      lines.push(`| ${target} | ${scroll === "auto" ? "scrolling" : "non-scrolling"} | ${f(median(pr))} (${f(min(pr))}–${f(Math.max(...pr))}) | ${f(median(tr))} | ${f(median(m.map((x) => x.mainPssKB)) / 1024)} | ${f(median(st))} (${f(pct(st, 95))}) | ${m.length} |`);
    }
  lines.push("");
}

lines.push("### Machine load per batch", "");
lines.push("Gate: 1-minute load < 3 and no cc1plus/ninja/podman/ld/ldc2/rustc process. `timeout-noisy` = the machine did" +
  " not get quiet within the wait window and the batch ran anyway; its numbers carry that load.", "");
lines.push("| batch | gate | waited, min | load1 at start → end | build processes at start | top CPU consumers at start (%) |");
lines.push("|---|---|---:|---|---|---|");
for (const b of R.batches) {
  const top = b.gate.top.filter((t) => t.cpu >= 5).slice(0, 4).map((t) => `${shortCmd(t.command)} ${t.cpu.toFixed(0)}`).join(", ") || "none ≥ 5%";
  lines.push(`| ${b.label} | ${b.gate.status} | ${b.gate.waitedMin} | ${b.gate.load1} → ${b.after?.load1 ?? "—"} | ${b.gate.buildProcs.length ? [...new Set(b.gate.buildProcs.map((p) => p.split(":")[0]))].join(", ") : "none"} | ${top} |`);
}
lines.push("");
const ov = excluded;
const loads = [...R.runs, ...R.mem].map((r) => r.load1AtStart).filter((x) => x != null);
lines.push(`Process runs that overlapped a build process (checked before and after each run), EXCLUDED from the tables above and re-measured: **${ov.length}**` +
  (ov.length ? ` (${[...new Set(ov.map((r) => `${r.target} ${r.scroll}${r.n ? " N=" + r.n : " mem"}`))].join("; ")})` : "") +
  `. 1-minute load at the start of each process run: median ${f(median(loads))}, max ${f(Math.max(...loads))}.`, "");

const section = lines.join("\n");
if (!doc) {
  process.stdout.write(section + "\n");
} else {
  const txt = fs.readFileSync(doc, "utf8");
  const re = /(<!-- results:begin -->\n)[\s\S]*?(<!-- results:end -->)/;
  if (!re.test(txt)) throw new Error(`${doc}: results markers not found`);
  fs.writeFileSync(doc, txt.replace(re, `$1${section}\n$2`));
  console.error(`updated ${doc}`);
}
